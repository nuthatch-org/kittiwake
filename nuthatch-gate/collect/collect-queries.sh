#!/usr/bin/env bash
# Regenerate nuthatch-gate's query sets from this checkout's source. Run on purpose, review the diff.
#
#   nuthatch-gate/collect/collect-queries.sh [<set>]   print one set (default alloc)
#   nuthatch-gate/collect/collect-queries.sh --write   rewrite every nuthatch-gate/<set>-queries.tsv
#   nuthatch-gate/collect/collect-queries.sh --check   exit 1 if any committed set is stale
#
# Sets: alloc, qos, gns, dips, data-services, staking-archive, one per production nest.
# Compiles collect/main.rs against a copy of crates/read/src/sql.rs with plain rustc (edition 2024,
# no cargo, no dependencies), plus extract.rs, which this script cuts from the four files that hold
# the rest of what the sets ask (the names job's statement, the census services, the dips stages,
# the SQL page's sample). Statements built from those refresh themselves; the ones main.rs marks
# `inline` are hand copies, so re-read those call sites too:
#   grep -rn 'NestId::' crates --include='*.rs' | grep -v /tests/
# Lodestar itself sends nothing to the nests: its dashboard reads kittiwake's API, so its share of
# a set is what kittiwake's read routes ask on its behalf.
# --check compares every set, its four header lines aside.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
kw=$(cd "$here/../.." && pwd)
src=$kw/crates/read/src/sql.rs
db=$kw/crates/db/src/lib.rs
names=$kw/crates/ingest/src/names.rs
census=$kw/crates/read/src/census.rs
stages=$kw/crates/read/src/dips_agreements.rs
sqlplay=$kw/crates/sqlplay/src/lib.rs
die() { echo "collect-queries: $*" >&2; exit 2; }
for f in "$src" "$db" "$names" "$census" "$stages" "$sqlplay"; do [ -f "$f" ] || die "no $f"; done
command -v rustc >/dev/null || die "rustc not on PATH"

excluded=$(sed -n 's/^pub const INDEXERS_EXCLUDED: &str = "\(0x[0-9a-f]*\)";$/\1/p' "$db")
[ -n "$excluded" ] || { echo "collect-queries: INDEXERS_EXCLUDED not found in $db" >&2; exit 1; }

work=$(mktemp -d "${TMPDIR:-/tmp}/collect-queries.XXXXXX")
trap 'rm -rf "$work"' EXIT
cp "$here/main.rs" "$work/main.rs"
# sql.rs re-exports one constant from kittiwake_db; inline it so the file stands alone.
sed "s|^pub use kittiwake_db::INDEXERS_EXCLUDED;|pub const INDEXERS_EXCLUDED: \&str = \"$excluded\";|" \
  "$src" > "$work/sql.rs"
grep -q 'kittiwake_db' "$work/sql.rs" && { echo "collect-queries: sql.rs still names kittiwake_db" >&2; exit 1; }

# Each cut is a whole item, copied verbatim, so a change to it changes the set.
{
  awk '/^pub const DEFAULT_NAMES_SQL: &str =/{p=1} p{print} p&&/;$/{exit}' "$names"
  awk '/^pub const LIST_TABLES: &str =/{p=1} p{print} p&&/;$/{exit}' "$sqlplay"
  awk '/^pub const STAKING_SAMPLE: &str =/{p=1} p{print} p&&/;$/{exit}' "$sqlplay"
  # From the Probe enum through registry_sql: plain data and one format!, no serde.
  awk '/^pub enum Probe \{/{p=1} p{print} /^pub fn registry_sql/{f=1} f&&/^}$/{exit}' "$census"
  # The Stage enum, STAGES and Stage::table; the rest of the impl needs the fold's types.
  awk '/^pub enum Stage \{/{p=1; print "#[derive(Clone, Copy)]"} p{print}
       /^impl Stage \{/{i=1} i&&/^    }$/{print "}"; exit}' "$stages"
} > "$work/extract.rs"
for want in 'pub const DEFAULT_NAMES_SQL' 'pub const LIST_TABLES' 'pub const SERVICES' \
  'pub fn registry_sql' 'pub const STAGES' 'pub fn table'; do
  grep -q "$want" "$work/extract.rs" || { echo "collect-queries: could not cut '$want' from kittiwake's source" >&2; exit 1; }
done

rustc --edition 2024 -O -o "$work/collect" "$work/main.rs" >&2

kw_rev=$(git -C "$kw" rev-parse --short=12 HEAD 2>/dev/null || echo unknown)
emit() {
  cat <<HDR
# $("$work/collect" --describe "$1")
# Generated by nuthatch-gate/collect/collect-queries.sh $1 from kittiwake $kw_rev on $(date -u +%Y-%m-%d).
# Do not hand-edit; change nuthatch-gate/collect/main.rs and regenerate.
# id<TAB>consumer<TAB>call site<TAB>sql
HDR
  "$work/collect" "$1"
}

case "${1:-alloc}" in
  --check)
    stale=0
    for set in $("$work/collect" --sets); do
      committed=$kw/nuthatch-gate/$set-queries.tsv
      if [ ! -f "$committed" ]; then
        echo "collect-queries: no $committed; generate it with --write" >&2
        stale=1
      elif ! diff <(tail -n +5 "$committed") <("$work/collect" "$set") >&2; then
        echo "collect-queries: $committed is stale; regenerate it" >&2
        stale=1
      fi
    done
    exit "$stale"
    ;;
  --write)
    for set in $("$work/collect" --sets); do
      emit "$set" > "$kw/nuthatch-gate/$set-queries.tsv"
      echo "collect-queries: wrote nuthatch-gate/$set-queries.tsv ($(grep -cv '^#' "$kw/nuthatch-gate/$set-queries.tsv") statements)" >&2
    done
    ;;
  -*) die "unknown option $1" ;;
  *)
    "$work/collect" --sets | grep -qx "$1" || die "no set named $1; the sets are: $("$work/collect" --sets | tr '\n' ' ')"
    emit "$1"
    ;;
esac
