#!/usr/bin/env bash
# Regenerate nuthatch-gate/alloc-queries.tsv from this checkout's source. Run on purpose, review the diff.
#
#   nuthatch-gate/collect/collect-queries.sh > nuthatch-gate/alloc-queries.tsv
#   nuthatch-gate/collect/collect-queries.sh --check
#
# Compiles collect/main.rs against a copy of crates/read/src/sql.rs with plain rustc (edition 2024,
# no cargo, no dependencies). Statements built in sql.rs refresh themselves; the ones main.rs marks
# `inline` are hand copies, so re-read those call sites too:
#   grep -rn 'NestId::Alloc' crates --include='*.rs' | grep -v /tests/
# Lodestar itself sends nothing to the nest: its dashboard reads kittiwake's API, so its share of
# the set is what kittiwake's read routes ask on its behalf.
# --check exits 1 if the committed set differs from a fresh run, its four header lines aside.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
kw=$(cd "$here/../.." && pwd)
src=$kw/crates/read/src/sql.rs
db=$kw/crates/db/src/lib.rs
[ -f "$src" ] || { echo "collect-queries: no $src" >&2; exit 2; }
[ -f "$db" ] || { echo "collect-queries: no $db" >&2; exit 2; }
command -v rustc >/dev/null || { echo "collect-queries: rustc not on PATH" >&2; exit 2; }

excluded=$(sed -n 's/^pub const INDEXERS_EXCLUDED: &str = "\(0x[0-9a-f]*\)";$/\1/p' "$db")
[ -n "$excluded" ] || { echo "collect-queries: INDEXERS_EXCLUDED not found in $db" >&2; exit 1; }

work=$(mktemp -d "${TMPDIR:-/tmp}/collect-queries.XXXXXX")
trap 'rm -rf "$work"' EXIT
cp "$here/main.rs" "$work/main.rs"
# sql.rs re-exports one constant from kittiwake_db; inline it so the file stands alone.
sed "s|^pub use kittiwake_db::INDEXERS_EXCLUDED;|pub const INDEXERS_EXCLUDED: \&str = \"$excluded\";|" \
  "$src" > "$work/sql.rs"
grep -q 'kittiwake_db' "$work/sql.rs" && { echo "collect-queries: sql.rs still names kittiwake_db" >&2; exit 1; }

rustc --edition 2024 -O -o "$work/collect" "$work/main.rs" >&2

if [ "${1:-}" = --check ]; then
  committed=$kw/nuthatch-gate/alloc-queries.tsv
  if ! diff <(tail -n +5 "$committed") <("$work/collect") >&2; then
    echo "collect-queries: $committed is stale; regenerate it" >&2
    exit 1
  fi
  exit 0
fi

kw_rev=$(git -C "$kw" rev-parse --short=12 HEAD 2>/dev/null || echo unknown)
cat <<HDR
# The allocations nest's query set: what Lodestar (via kittiwake's read API) and kittiwake's jobs
# send to its /sql. Generated by nuthatch-gate/collect/collect-queries.sh from kittiwake $kw_rev on $(date -u +%Y-%m-%d).
# Do not hand-edit; change nuthatch-gate/collect/main.rs and regenerate.
# id<TAB>consumer<TAB>call site<TAB>sql
HDR
"$work/collect"
